const messages: Record<Locale, Record<MessageKey, string>> = { zh, en };
let currentLocale: Locale = 'zh';

export function getLocale(): Locale { return currentLocale; }
export function setLocale(locale: Locale): void { currentLocale = locale; }
export function localeLabel(locale: Locale): string { return locale === 'zh' ? '中文' : 'English'; }
export function messageKeys(): MessageKey[] { return Object.keys(zh) as MessageKey[]; }

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const template = messages[currentLocale][key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}
